import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {auditExportLimit,auditFileLimit,filterSavedValidatorAudit,parseSavedValidatorAudit,readSavedValidatorAudit,reviewSavedValidatorAudit} from '../src/saved-validator-audit.js';

function row(action,outcome,time='2026-11-15T12:00:00+00:00') {
 return {recorded_at_utc:time,operator_id:'fixture operator',remote_address:'192.0.2.21',
  action:`validator.operations.${action}`,outcome,...(action==='cluster_status'?{}:{validator_id:'fixture validator'})};
}

const jsonl = (...rows)=>rows.map(value=>`${JSON.stringify(value)}\n`).join('');

test('keeps exact UTC order, filters inclusive UTC days and does not join authorization with a reported outcome',()=>{
 const values=parseSavedValidatorAudit(jsonl(
  row('lifecycle.restart','authorized:execution_pending','2026-11-15T23:59:59.999999999+00:00'),
  row('lifecycle.restart','success','2026-11-16T00:00:00Z'),
  row('lifecycle','denied:ScopeRequired','2026-11-15T00:00:00Z'),
  row('cluster_status','unavailable','2026-11-15T00:00:00.000000001Z'),
  row('status','success','2026-11-14T23:59:59.999999999+00:00'),
  row('logs','success','2026-11-15T00:00:00.000000001Z'),
 ));
 assert.deepEqual(values.map(({id})=>id),[2,1,4,6,3,5]);
 const today=filterSavedValidatorAudit(values,{from:'2026-11-15',through:'2026-11-15'});
 assert.deepEqual(today.map(({id})=>id),[1,4,6,3]);
 const restart=filterSavedValidatorAudit(today,{action:'lifecycle.restart',outcome:'authorized:execution_pending'});
 assert.deepEqual(restart.map(({id})=>id),[1]);
 const result=reviewSavedValidatorAudit(restart,new Set([1]));
 assert.deepEqual(result,{schema:'nodenetwork-saved-validator-management-audit-v1',entries:[{
  savedLine:1,recordedAtUtc:'2026-11-15T23:59:59.999999999+00:00',action:'validator.operations.lifecycle.restart',outcome:'authorized:execution_pending',
 }]});
 assert.doesNotMatch(JSON.stringify(result),/fixture operator|192\.0\.2\.21|fixture validator/);
 assert.throws(()=>filterSavedValidatorAudit(values,{from:'2026-11-16',through:'2026-11-15'}),/first UTC day/);
 assert.throws(()=>reviewSavedValidatorAudit(restart,new Set([2])),/current filter/);
});

test('refuses ambiguous, incomplete, and unsupported owner records or outcome combinations',()=>{
 const good=row('preflight','success');
 for (const input of [
  jsonl({...good,token:'unexpected'}),jsonl({...good,validator_id:undefined}),jsonl({...good,recorded_at_utc:'2026-02-31T00:00:00Z'}),
  jsonl(row('preflight','authorized:execution_pending')),jsonl(row('lifecycle','success')),
  jsonl(row('lifecycle.stop','denied:ScopeRequired')),jsonl(row('snapshot.capture','unavailable')),
  jsonl(row('cluster_status','success'),{...row('cluster_status','success'),validator_id:'unexpected'}),
  jsonl(row('logs','denied:free text')),jsonl(row('__proto__','success')),
  jsonl(good).replace('"outcome":"success"','"outcome":"success","outc\\u006fme":"success"'),
  `${jsonl(good)}\n`,jsonl({...good,operator_id:'a'.repeat(4096)}),
 ]) assert.throws(()=>parseSavedValidatorAudit(input),/unsupported validator management audit record/);
 assert.throws(()=>parseSavedValidatorAudit(jsonl(good).trimEnd()),/complete/);
 assert.deepEqual(parseSavedValidatorAudit(''),[]);
 assert.throws(()=>parseSavedValidatorAudit(jsonl(good).repeat(2049)),/2,048 records/);
 const records=parseSavedValidatorAudit(jsonl(good).repeat(auditExportLimit+1));
 assert.throws(()=>reviewSavedValidatorAudit(records,new Set(records.map(record=>record.id))),/current filter/);
});

test('enforces UTF-8 and complete bytes, retires permission loss after a pending read, and bounds selection before reading',async()=>{
 await assert.rejects(readSavedValidatorAudit({size:auditFileLimit+1,arrayBuffer:()=>assert.fail('unexpected read')}),/at most 4 MiB/);
 await assert.rejects(readSavedValidatorAudit(new Blob([new Uint8Array([255,10])])),/as UTF-8/);
 await assert.rejects(readSavedValidatorAudit({size:1,arrayBuffer:async()=>new ArrayBuffer(0)}),/in full/);
 assert.equal(await readSavedValidatorAudit({size:1,arrayBuffer:()=>assert.fail('retired read')},()=>false),null);
 const good=new Blob([jsonl(row('preflight','success'))]);
 let active=true;
 assert.equal(await readSavedValidatorAudit({size:good.size,arrayBuffer:()=>{active=false;return good.arrayBuffer();}},()=>active),null);
});

